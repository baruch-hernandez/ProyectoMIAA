/** Rectángulo que encierra al estado: [[sur, oeste], [norte, este]]. */
export const CAJA_AGS: [[number, number], [number, number]] = [
  [21.62227, -102.87418],
  [22.45959, -101.83529],
];

/**
 * ¿El punto cae dentro del estado? Algoritmo de "lanzar un rayo" (ray casting):
 * se traza una línea horizontal desde el punto y se cuentan los cruces con el
 * contorno. Número impar de cruces = adentro. Es el mismo algoritmo del backend.
 */
export function dentroDeAguascalientes({ lat, lng }: Coordenadas): boolean {
  // Filtro rápido: si está fuera del rectángulo, no hace falta recorrer el contorno
  if (lat < CAJA_AGS[0][0] || lat > CAJA_AGS[1][0] || lng < CAJA_AGS[0][1] || lng > CAJA_AGS[1][1]) return false;

  let dentro = false;
  for (let i = 0, j = CONTORNO_AGS.length - 1; i < CONTORNO_AGS.length; j = i++) {
    const [latI, lngI] = CONTORNO_AGS[i];
    const [latJ, lngJ] = CONTORNO_AGS[j];
    const cruza = latI > lat !== latJ > lat && lng < ((lngJ - lngI) * (lat - latI)) / (latJ - latI) + lngI;
    if (cruza) dentro = !dentro;
  }
  return dentro;
}

